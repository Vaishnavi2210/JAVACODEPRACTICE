package Interview_Programs.practice;

public class Print_1_to_100_without_using_numbers {

    public static void main(String[] args) {

        int one = "b".length();
        int hundread = "bbbbbbbbbb".length() * "bbbbbbbbbb".length();

        for(int i = one; i <= hundread; i++){
            System.out.println(i);
        }
    }
}
